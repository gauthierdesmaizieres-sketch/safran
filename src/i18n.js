export const DICT = { de: {}, en: {} }
for (const [fr, de, en] of ROWS) { DICT.de[fr] = de; DICT.en[fr] = en }

function pick() {
  if (typeof document === 'undefined') return 'fr' // node unit tests run on the French text
  let saved = null
  try { saved = localStorage.getItem(KEY) } catch { /* private mode */ }
  const l = saved || navigator.language.slice(0, 2)
  return l in LANGS ? l : 'fr'
}
export const LANG = pick()
export const LOCALE = { fr: 'fr-FR', de: 'de-DE', en: 'en-GB' }[LANG]
if (typeof document !== 'undefined') document.documentElement.lang = LANG

// Module-level labels (MEALS, TAGS…) are translated once at load, so a switch reloads the page.
export function setLang(l) {
  try { localStorage.setItem(KEY, l) } catch { /* private mode: stays on the phone's language */ }
  location.reload()
}

export function t(fr, vars) {
  const s = DICT[LANG]?.[fr] ?? fr
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => vars[k]) : s
}

// French "1,5 portion" is singular, German/English "1.5 servings" plural: let Intl decide.
export function tn(n, one, many, vars) {
  return t(new Intl.PluralRules(LOCALE).select(n) === 'one' ? one : many, { n, ...vars })
}
